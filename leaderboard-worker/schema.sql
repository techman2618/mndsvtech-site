CREATE TABLE IF NOT EXISTS scores(id INTEGER PRIMARY KEY AUTOINCREMENT,name TEXT NOT NULL,score INTEGER NOT NULL,created INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS scores_top ON scores(score DESC,created ASC);
CREATE TABLE IF NOT EXISTS runs(id TEXT PRIMARY KEY,ip TEXT NOT NULL,started INTEGER NOT NULL,used INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS hits(ip TEXT NOT NULL,ts INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS hits_ip ON hits(ip,ts);
CREATE TABLE IF NOT EXISTS tm_scores(id INTEGER PRIMARY KEY AUTOINCREMENT,name TEXT NOT NULL,score INTEGER NOT NULL,created INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS tm_top ON tm_scores(score DESC,created ASC);
